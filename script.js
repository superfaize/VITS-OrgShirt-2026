const gallery = document.querySelector("#gallery");
const detailOverlay = document.querySelector("#detail-overlay");
const lightbox = document.querySelector("#lightbox");
const detailContent = document.querySelector("#detail-content");
const lightboxImage = document.querySelector("#lightbox-image");
let activeEntryIndex = 0;
let activeImageIndex = 0;
let zoom = 1;

function placeholderImage(label, accent = "1264d6") {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 600"><rect width="800" height="600" fill="#d9e7f2"/><path d="M0 460L230 270l100 85 130-170 340 275H0Z" fill="#${accent}" opacity=".92"/><circle cx="650" cy="145" r="82" fill="#5fd6e8" opacity=".75"/><text x="50" y="530" fill="#0c1b2a" font-family="Arial" font-size="30" font-weight="700">${label}</text></svg>`;
  return `data:image/svg+xml;charset=UTF-8,${encodeURIComponent(svg)}`;
}

function useImageFallback(image, label) {
  image.addEventListener("error", () => {
    if (!image.dataset.fallback) {
      image.dataset.fallback = "true";
      image.src = placeholderImage(label);
    }
  });
}

function renderGallery() {
  gallery.innerHTML = designEntries.map((entry, index) => `
    <article class="entry-card" style="animation-delay: ${index * 70}ms" data-entry-index="${index}" tabindex="0" role="button" aria-label="Open Entry #${entry.number}">
      <img class="entry-image" src="${entry.image}" alt="Entry #${entry.number} design" data-fallback-label="ENTRY #${entry.number}">
      <div class="entry-content"><span class="entry-badge">Entry #${entry.number}</span></div>
    </article>`).join("");
  gallery.querySelectorAll("img").forEach((image) => useImageFallback(image, image.dataset.fallbackLabel));
  gallery.querySelectorAll("[data-entry-index]").forEach((card) => {
    card.addEventListener("click", () => openDetail(Number(card.dataset.entryIndex)));
    card.addEventListener("keydown", (event) => { if (event.key === "Enter" || event.key === " ") { event.preventDefault(); openDetail(Number(card.dataset.entryIndex)); } });
  });
}

function openDetail(index) {
  activeEntryIndex = index;
  const entry = designEntries[index];
  const explanationImages = (entry.explanationImages || []).map((image, imageIndex) => `
    <img class="explanation-image" src="${image}" alt="Entry #${entry.number} explanation page ${imageIndex + 1}" data-fallback-label="ENTRY #${entry.number} EXPLANATION ${imageIndex + 1}">`).join("");
  detailContent.innerHTML = `
    <div class="modal-entry">
      <img class="shirt-image" src="${entry.image}" alt="Entry #${entry.number} design" data-fallback-label="ENTRY #${entry.number}">
      <div class="modal-copy"><span class="entry-badge">Entry #${entry.number}</span><div class="entry-meta"><p><strong>Name:</strong> ${entry.name}</p><p><strong>Section:</strong> ${entry.section}</p></div><p>${entry.explanation}</p>${explanationImages}</div>
    </div>`;
  detailContent.querySelectorAll("img").forEach((image) => {
    useImageFallback(image, image.dataset.fallbackLabel);
    image.addEventListener("click", () => openLightbox(image.src, image.alt));
  });
  detailOverlay.classList.add("is-open");
  detailOverlay.setAttribute("aria-hidden", "false");
  document.body.classList.add("is-locked");
}

function closeDetail() {
  detailOverlay.classList.remove("is-open");
  detailOverlay.setAttribute("aria-hidden", "true");
  if (!lightbox.classList.contains("is-open")) document.body.classList.remove("is-locked");
}

let lightboxSource = "";
let lightboxAlt = "";

function openLightbox(source, alt) {
  lightboxSource = source;
  lightboxAlt = alt;
  zoom = 1;
  updateLightbox();
  lightbox.classList.add("is-open");
  lightbox.setAttribute("aria-hidden", "false");
  document.body.classList.add("is-locked");
}

function updateLightbox() {
  const entry = designEntries[activeEntryIndex];
  lightboxImage.src = lightboxSource || entry.image;
  lightboxImage.alt = lightboxAlt || `Entry #${entry.number} design`;
  lightboxImage.style.transform = `scale(${zoom})`;
  document.querySelector("#zoom-label").textContent = `${Math.round(zoom * 100)}%`;
  useImageFallback(lightboxImage, `ENTRY #${entry.number}`);
}

function closeLightbox() {
  lightbox.classList.remove("is-open");
  lightbox.setAttribute("aria-hidden", "true");
  if (!detailOverlay.classList.contains("is-open")) document.body.classList.remove("is-locked");
}

function setupQrCode() {
  document.querySelectorAll("[data-form-link]").forEach((link) => link.href = GOOGLE_FORM_URL);
}

renderGallery();
setupQrCode();
document.querySelector("#detail-close").addEventListener("click", closeDetail);
document.querySelector("#lightbox-close").addEventListener("click", closeLightbox);
document.querySelector("#zoom-in").addEventListener("click", () => { zoom = Math.min(zoom + .25, 3); updateLightbox(); });
document.querySelector("#zoom-out").addEventListener("click", () => { zoom = Math.max(zoom - .25, .5); updateLightbox(); });
document.querySelector("#zoom-reset").addEventListener("click", () => { zoom = 1; updateLightbox(); });
detailOverlay.addEventListener("click", (event) => { if (event.target === detailOverlay) closeDetail(); });
lightbox.addEventListener("click", (event) => { if (event.target === lightbox) closeLightbox(); });
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") { if (lightbox.classList.contains("is-open")) closeLightbox(); else if (detailOverlay.classList.contains("is-open")) closeDetail(); }
});
